<h2>Informativa sui rimborsi</h2>
<p>La nostra informativa sui resi entro 60 giorni prevede che, dopo la ricezione di un articolo, hai 30 giorni di tempo per richiedere un reso.</p>
<p>Perché sia idoneo al reso, l'articolo deve essere nelle stesse condizioni in cui lo hai ricevuto, non deve essere stato aperto o utilizzato e deve essere contenuto nell'imballaggio originario. Inoltre, avrai bisogno della ricevuta o fattura d'acquisto.</p>
<p>Per avviare un reso, contattaci all'indirizzo <a href="mailto:info@lamess.it">info@lamess.it</a>. I resi dovranno essere spediti all'indirizzo che verrà fornito dopo aver accettato il reso.</p>
<p>Se il reso viene accettato, ti invieremo un'etichetta di spedizione per il reso e le istruzioni su come e dove spedire il pacco. Gli articoli inviati senza una precedente richiesta di reso non saranno accettati.</p>
<p>Per qualsiasi domanda sui resi, contattaci in qualsiasi momento all'indirizzo <a href="mailto:info@lamess.it">info@lamess.it</a>.</p>
<h3>Danni e problemi</h3>
<p>Ispeziona l'ordine al momento della ricezione e contattaci immediatamente in caso di difetti o danni o se hai ricevuto l'articolo sbagliato. In questo modo, potremo valutare il problema e fare in modo di risolverlo.</p>
<h3>Eccezioni / articoli non restituibili</h3>
<p>Determinati tipi di articoli non possono essere restituiti, come i beni deperibili i prodotti su misura (ad esempio ordini speciali o articoli personalizzati) e i prodotti per la cura della persona se la confezione è stata aperta. Inoltre, non accettiamo il reso di materiali pericolosi, liquidi infiammabili o gas. Se hai domande o dubbi su un articolo specifico, non esitare a contattarci.</p>
<p>Sfortunatamente non possiamo accettare il reso di articoli in promo o buoni regalo.</p>
<h3>Sostituzioni</h3>
<p>Il modo più rapido per assicurarti di ricevere ciò che desideri è restituire l'articolo ricevuto e, quando il reso sarà stato accettato, acquistare il nuovo articolo a parte.</p>
<h3>Periodo di riflessione di 14 giorni per l'Unione Europea</h3>
<p>Nonostante quanto sopra affermato, se la merce viene spedita nell'Unione Europea, hai il diritto di annullare o restituire l'ordine entro 60 giorni per qualsiasi motivo e senza dover fornire alcuna giustificazione. Come sopra, l'articolo deve essere nelle stesse condizioni in cui lo hai ricevuto, non deve essere stato indossato o utilizzato, deve avere tutti i cartellini e deve essere contenuto nell'imballaggio originario. Inoltre, avrai bisogno della ricevuta o di una prova d'acquisto.</p>
<h3>Rimborsi</h3>
<p>Non appena avremo ricevuto e ispezionato il tuo reso, ti avviseremo per comunicarti se il rimborso è stato approvato o meno. In caso di approvazione, entro 10 giorni lavorativi riceverai il rimborso in automatico attraverso il metodo di pagamento originario. Potrebbe volerci del tempo prima che la banca o la società che ha emesso la carta di credito elaborino e rendano visibile il rimborso.</p>
<p>Una volta passati più di 15 giorni lavorativi dall'approvazione del reso, contattaci all'indirizzo info@coffeeroom.it.</p>
<h2>Politica di Resi e Rimborsi</h2>
<p>La soddisfazione dei nostri clienti è la nostra priorità. Tuttavia, essendo i nostri prodotti alimenti deperibili, non possiamo accettare resi o cambi per motivi igienici e di sicurezza.</p>
<h3>Prodotti non restituibili</h3>
<p>Ai sensi delle normative vigenti, non possiamo accettare resi o rimborsi per i seguenti articoli:</p>
<ul>
 <li>Caffè, tè, tisane, o altri prodotti alimentari aperti o non sigillati</li>
 <li>Prodotti danneggiati a causa di uso improprio da parte del cliente</li>
 <li>Capsule o cialde acquistate per errore</li>
</ul>
<h3>Resi ammessi (solo se difettosi o errati)</h3>
<p>Accettiamo richieste di reso esclusivamente nei seguenti casi:</p>
<ul>
 <li>Hai ricevuto un prodotto danneggiato o difettoso</li>
 <li>Hai ricevuto un prodotto diverso da quello ordinato</li>
</ul>
<p>In questi casi, ti preghiamo di contattarci entro 7 giorni dalla ricezione dell’ordine all’indirizzo email: <a href="mailto:info@lamess.it">info@lamess.it</a>, allegando:</p>
<ul>
 <li>Numero dell’ordine</li>
 <li>Foto del prodotto ricevuto</li>
 <li>Descrizione del problema</li>
</ul>
<p>Dopo aver esaminato la richiesta, ti invieremo le istruzioni per il reso o ti forniremo un rimborso/parziale rimborso a seconda del caso.</p>
<h3>Spedizione per i resi</h3>
<p>Se il reso viene approvato:</p>
<ul>
 <li>Ti forniremo un'etichetta di spedizione prepagata (solo in caso di errore nostro)</li>
 <li>In caso contrario, le spese di restituzione saranno a carico del cliente</li>
</ul>
<h3>Rimborsi</h3>
<p>Una volta ricevuto e ispezionato il prodotto restituito (se applicabile), ti invieremo una conferma via email. Se approvato, il rimborso verrà emesso entro 7 giorni lavorativi, utilizzando lo stesso metodo di pagamento usato per l’acquisto.</p>
<h3>Domande?</h3>
<p>Per qualsiasi chiarimento, puoi contattarci via email a <a href="mailto:info@lamess.it">info@lamess.it</a>.</p>
